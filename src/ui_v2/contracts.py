"""Structural contracts for replaceable widgets (no layouts or business imports)."""
from __future__ import annotations
from typing import Any, Optional, Protocol, runtime_checkable


@runtime_checkable
class ImagePreview(Protocol):
    def setPixmap(self, pixmap: Any) -> None: ...
    def set_markers(self, markers: list) -> None: ...
    def clear_markers(self) -> None: ...
    def clear_image(self) -> None: ...


@runtime_checkable
class PointCloudView(Protocol):
    status_changed: Any
    collapse_toggled: Any
    maximize_toggled: Any
    def set_pointcloud(self, camera_id: str, pcd: Any) -> None: ...
    def set_pointcloud_merged(self, pcd: Any) -> None: ...
    def remove_camera(self, camera_id: str) -> None: ...
    def clear_all(self) -> None: ...
    def reset_view(self) -> None: ...
    def set_view_preset(self, name: str) -> None: ...
    def set_point_size(self, size: int) -> None: ...
    def set_reference(self, camera_id: Optional[str]) -> None: ...
    def set_highlight(self, camera_id: str, indices: Optional[list] = None) -> None: ...
    def clear_highlight(self) -> None: ...
    def is_collapsed(self) -> bool: ...
    def set_collapsed(self, collapsed: bool) -> None: ...
    def set_maximized(self, on: bool) -> None: ...
