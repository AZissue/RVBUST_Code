// ── 使用说明的内容表 ──────────────────────────────────────────────────
//
// 界面上「帮助」打开的那本说明书，正文全部在这里，作为**纯数据**。界面
// （src/ui/HelpDialog.*）只负责把它渲染成左侧目录 + 右侧正文。
//
// 分两层，理由与 MeasureMethods.h 相同（那里存的是测量方法的元信息，这里是
// 使用说明的正文）：
//   * 说明文字里逐字写着界面上的按钮名、卡片名、文件名。改名而说明没跟上，
//     用户照着说明找不到东西 —— 这种失效不会报错，只会让人怀疑自己。放在
//     纯数据表里，tests/test_help_content.cpp 就能把「测量方法一章必须覆盖
//     每一个方法」「正文里不许写死版本号」钉住；
//   * 不依赖 Qt：正文是 UTF-8 的 std::string，界面侧 QString::fromUtf8 转换。
//
// 写正文时的三条约定：
//   1. **不许写死版本号**，用 kCurrentVersionToken，界面拿 AppInfo::version()
//      替换。2026-10-08 界面升到 2.0 还显示 V1.0，原因就是版本号被写死在三处；
//      说明里再写死一处，等于把这个坑重新挖一遍。
//   2. 测量方法一章是**生成**的（buildMeasureChapter()），不要手抄
//      MeasureMethods.h 的文案 —— 手抄就会分叉。
//   3. 界面元素一律用「」括起来（与界面代码、日志文案一致）；正文里不要出现
//      半角双引号，那是 C++ 字符串字面量的结束符。
//
// 按钮/卡片的名字取自 2026-10-08 的实机界面（见 STATUS.md 交接块之三）：
// 模式选择行是「手眼模式：」「标定方法：」「标记物类型：」三组，第二种标记物
// 叫「黑底白圆」（不是“非对称网格”）；操作按钮行里的读取按钮叫「拍照位姿」
// 与「戳点位姿」（不带“读取”前缀）。
