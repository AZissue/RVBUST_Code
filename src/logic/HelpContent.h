// 正文里的「当前版本」占位符。界面替换成 AppInfo::version()。
inline constexpr const char* kCurrentVersionToken = "%CURRENT_VERSION%";

struct Chapter {
    const char* id;      // 稳定 ASCII，用于 [文字](#id) 互链与单测
    const char* title;   // 左侧目录项
    const char* body;    // 右侧正文（QTextBrowser 的 Markdown 子集）
};

// ── 更新记录 ──────────────────────────────────────────────────────────
//
// 与「版本与更新记录」那一章的正文是两份写法，靠单测对上（每条 version/date
// 必须出现在正文里）。第一条必须就是 AppInfo::version() —— 升版本时忘写
// 更新记录，测试会断。
struct ChangeEntry {
    const char* version;
    const char* date;    // YYYY-MM-DD
    const char* notes;   // 一句话
};

