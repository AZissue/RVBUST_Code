inline int chapterCount()
{
    int n = 0;
    chapters(n);
    return n;
}

inline const Chapter* chapterById(const char* id)
{
    if (!id)
        return nullptr;
    int n = 0;
    const Chapter* table = chapters(n);
    for (int i = 0; i < n; ++i) {
        if (std::string(table[i].id) == id)
            return &table[i];
    }
    return nullptr;
}

// 找不到返回 -1（界面据此忽略正文里的死链，而不是默默跳到第一章）。
inline int chapterIndexOf(const char* id)
{
    if (!id)
        return -1;
    int n = 0;
    const Chapter* table = chapters(n);
    for (int i = 0; i < n; ++i) {
        if (std::string(table[i].id) == id)
            return i;
    }
    return -1;
}

// 把正文里的 kCurrentVersionToken 换成当前版本号。帮助文本自己绝不写死版本。
inline std::string renderBody(const std::string& body, const std::string& currentVersion)
{
    const std::string token = kCurrentVersionToken;
    std::string out = body;
    for (std::size_t pos = out.find(token); pos != std::string::npos;
         pos = out.find(token, pos + currentVersion.size())) {
        out.replace(pos, token.size(), currentVersion);
    }
    return out;
}

